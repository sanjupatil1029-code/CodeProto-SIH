import type { ApprovalDef } from "../types";

/**
 * These two business types have a precise, ordered checklist (as supplied) instead of
 * being derived from the generic rules engine in approvals.ts. Each step depends on the
 * one directly before it, keeping the roadmap strictly sequential and vertical.
 */

function chain(steps: Omit<ApprovalDef, "dependsOn" | "appliesTo">[]): ApprovalDef[] {
  return steps.map((s, idx) => ({
    ...s,
    dependsOn: idx === 0 ? [] : [steps[idx - 1].id],
    appliesTo: () => true,
  }));
}

